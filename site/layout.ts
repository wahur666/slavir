/** Shared HTML shell of the generated docs and wiki pages, see generate.ts */

export const GITHUB = "https://github.com/wahur666/slavir";

const ENTITIES: Record<string, string> = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"};

export function escapeHtml(text: string): string {
    return text.replace(/[&<>"']/g, char => ENTITIES[char]);
}

export interface PageOptions {
    title: string;
    description: string;
    /** "docs" or "wiki", highlights the top bar link */
    section: "docs" | "wiki";
    /** Main column HTML */
    body: string;
    /** Left column HTML, optional */
    sidebar?: string;
}

/**
 * A full page one folder below src/ (src/docs/*.html, src/wiki/*.html), so every local URL starts with "../". Vite
 * picks the pages up as build entries and bundles the stylesheets, the script and the images they reference.
 */
export function page({title, description, section, body, sidebar}: PageOptions): string {
    const current = (name: PageOptions["section"]) => (name === section ? ' aria-current="page"' : "");
    return `<!doctype html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="description" content="${escapeHtml(description)}">
    <link rel="icon" type="image/png" href="../assets/favicon.png">
    <link rel="stylesheet" href="../home.css">
    <link rel="stylesheet" href="../site.css">
    <title>${escapeHtml(title)} · Slavir</title>
</head>
<body class="site">
    <!-- Generated by site/generate.ts, do not edit -->
    <header class="topbar">
        <a class="brand" href="../">
            <img src="../assets/favicon.png" alt="" width="28" height="28">
            <span>Slavir</span>
        </a>
        <nav>
            <a href="../play/">Play</a>
            <a href="../wiki/"${current("wiki")}>Units</a>
            <a href="../docs/"${current("docs")}>Docs</a>
            <a href="${GITHUB}" rel="noopener">GitHub</a>
        </nav>
    </header>
    <div class="site-layout${sidebar ? "" : " no-sidebar"}">
        ${sidebar ? `<aside class="site-sidebar">${sidebar}</aside>` : ""}
        <main class="site-main">
${body}
        </main>
    </div>
    <footer class="footer">
        <p>Slavir is free software under the GPL-3.0-or-later license.
            <a href="${GITHUB}" rel="noopener">Source on GitHub</a> ·
            <a href="${GITHUB}/issues" rel="noopener">Report an issue</a></p>
    </footer>
    <script type="module" src="../site.ts"></script>
</body>
</html>
`;
}
